    @classmethod
    def _generate_ai_image(
        cls,
        prompt: str,
        negative_prompt: str = "",
        aspect_ratio: str = "1:1",
        style_preset: str = "photographic",
        seed: int = 0,
        output_format: str = "webp",
        reference_image: Optional[bytes] = None,
        image_strength: float = 0.35,
        reference_mode: str = "img2img",
        style_fidelity: float = 0.5,
        deadline: Optional[float] = None,
    ) -> Optional[bytes]:
        """
        Call Stability AI API to generate an image.

        Three modes are supported:

        - txt2img: no `reference_image`. Pure text-to-image against
          STABILITY_API_URL (e.g. SD3 Ultra). `aspect_ratio` is honored.

        - img2img (default when `reference_image` is provided):
          Posts the reference to STABILITY_API_URL with a `strength` field.
          Output inherits the reference's framing & composition.
          `image_strength`: 0.0 = identical to reference, 1.0 = reference
          ignored. Best for chaining a previous full-body shot.

        - style: Posts the reference to STABILITY_CONTROL_STYLE_URL (the
          Stability `/v2beta/stable-image/control/style` endpoint). Identity
          and visual character are taken from the reference, but framing,
          pose, outfit and scene come from the prompt. `aspect_ratio` IS
          honored here, unlike img2img. `style_fidelity` (0.0-1.0)
          controls how strongly the output binds to the reference.
          Best when the reference is a portrait but a full-body shot is
          wanted, or when the prompt asks for specific outfit/scene changes.

        The prohibited-subject policy is re-asserted here as the last gate
        before the provider is contacted, so no caller — view, service, Celery
        task, or a direct call to this helper — can dispatch a prompt involving
        children, animals or deceased people. Violations raise
        ``ProhibitedImageSubjectError`` rather than returning None, so they are
        never mistaken for a provider failure that should trigger a fallback.

        Returns image bytes on success, None on failure.
        """
        import requests
        from django.conf import settings

        ImagePromptPolicy.assert_allowed(prompt, negative_prompt)

        api_key = getattr(settings, "STABILITY_API_KEY", None)
        api_url = getattr(settings, "STABILITY_API_URL", None)
        api_model = getattr(settings, "STABILITY_MODEL", "sd3.5-large-turbo")
        control_style_url = getattr(
            settings,
            "STABILITY_CONTROL_STYLE_URL",
            "https://api.stability.ai/v2beta/stable-image/control/style",
        )

        if not api_key:
            logger.error("Stability AI credentials not configured")
            return None
        if deadline is None:
            deadline = time.monotonic() + float(getattr(settings, "IMAGE_GENERATION_TOTAL_TIMEOUT_SECONDS", 180))

        headers = {
            "authorization": f"Bearer {api_key}",
            "accept": "image/*",
        }

        # ---------- Choose endpoint + payload shape based on mode ----------
        if reference_image and reference_mode == "style":
            # /control/style: identity from reference, framing/outfit from prompt.
            target_url = control_style_url
            data = {
                "prompt": prompt,
                "negative_prompt": negative_prompt,
                "output_format": output_format,
                "aspect_ratio": aspect_ratio,
                "style_preset": style_preset,
                "fidelity": str(max(0.0, min(1.0, style_fidelity))),
            }
            if seed and seed != 0:
                data["seed"] = str(seed)
            files = {
                "image": ("reference.webp", reference_image, "image/webp"),
            }

        elif reference_image:
            # img2img against the main endpoint (e.g. SD3 Ultra).
            # aspect_ratio is intentionally omitted: img2img derives it from
            # the reference. `strength` is required when an image is sent.
            if not api_url:
                logger.error("STABILITY_API_URL not configured for img2img")
                return None
            target_url = api_url
            data = {
                "prompt": prompt,
                "negative_prompt": negative_prompt,
                "output_format": output_format,
                "style_preset": style_preset,
                "model": api_model,
                "strength": str(max(0.0, min(1.0, image_strength))),
            }
            if seed and seed != 0:
                data["seed"] = str(seed)
            files = {
                "image": ("reference.webp", reference_image, "image/webp"),
            }

        else:
            # txt2img (unchanged behaviour).
            if not api_url:
                logger.error("STABILITY_API_URL not configured for txt2img")
                return None
            target_url = api_url
            data = {
                "prompt": prompt,
                "negative_prompt": negative_prompt,
                "output_format": output_format,
                "aspect_ratio": aspect_ratio,
                "style_preset": style_preset,
                "model": api_model,
            }
            if seed and seed != 0:
                data["seed"] = str(seed)
            files = {"none": ""}

        try:
            response = cls._run_with_image_deadline(
                lambda: requests.post(  # nosec B113: positive bounded timeout from _remaining_image_timeout below
                    target_url,
                    headers=headers,
                    files=files,
                    data=data,
                    timeout=cls._remaining_image_timeout(deadline, 120),
                    stream=True,
                ),
                deadline,
            )
            response_bytes = cls._run_with_image_deadline(
                lambda: cls._read_and_close_bounded_response(
                    response,
                    deadline=deadline,
                    max_bytes=int(getattr(settings, "FAL_IMAGE_MAX_RESPONSE_BYTES", 15 * 1024 * 1024)),
                ),
                deadline,
            )
            if response.status_code == 200:
                return response_bytes
            error_detail = "Unknown error"
            try:
                error_detail = json.loads(response_bytes.decode("utf-8"))
            except SoftTimeLimitExceeded:
                raise
            except (UnicodeDecodeError, ValueError):
                error_detail = response_bytes[:500].decode("utf-8", errors="replace") or "Unknown error"
            logger.error(
                f"Stability AI error: mode={reference_mode if reference_image else 'txt2img'} "
                f"status={response.status_code} detail={error_detail}"
            )
            return None

        except SoftTimeLimitExceeded:
            raise
        except ImageGenerationDeadlineExceeded:
            raise
        except Exception:
            logger.exception("Unexpected error calling Stability AI")
            return None

    @staticmethod
    def _remaining_image_timeout(deadline: float, fallback: float) -> float:
        """Return the remaining shared budget for the next blocking call."""
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise ImageGenerationDeadlineExceeded
        return max(0.1, min(float(fallback), remaining))

    @classmethod
    def _run_image_billing_operation(cls, operation, deadline: float):
        """Run one billing transition with bounded PostgreSQL lock waits."""
        from django.conf import settings

        max_wait = float(getattr(settings, "IMAGE_BILLING_DB_MAX_WAIT_SECONDS", 2))
        remaining = max(0.001, deadline - time.monotonic())
        timeout_ms = max(1, int(min(max_wait, remaining) * 1000))
        with transaction.atomic():
            if connection.vendor == "postgresql":
                with connection.cursor() as cursor:
                    cursor.execute(
                        "SELECT set_config('lock_timeout', %s, true), " "set_config('statement_timeout', %s, true)",
                        [f"{timeout_ms}ms", f"{timeout_ms}ms"],
                    )
            return operation()

    @classmethod
    def _refund_image_reservation(cls, reservation, *, reason: str, deadline: float) -> None:
        """Attempt a bounded refund and enqueue durable recovery on failure."""
        if reservation is None:
            return
        try:
            cls._run_image_billing_operation(
                lambda: PaidFeature.refund(reservation, reason=reason),
                deadline,
            )
        except (ReservationError, BillingReservation.DoesNotExist, CustomUser.DoesNotExist):
            # Erasure can cascade the hold while a gallery provider is running.
            # There is then no account/pool to credit, and a rejected
            # publication must still return its controlled failure response.
            if not BillingReservation.objects.filter(pk=reservation.pk).exists():
                logger.info("Image refund skipped for erased reservation=%s", reservation.pk)
                return
            raise
        except (OperationalError, ImageGenerationDeadlineExceeded):
            logger.exception(
                "Image refund deferred for reservation=%s reason=%s",
                getattr(reservation, "reservation_id", reservation),
                reason,
            )
            try:
                from capp.tasks import refund_billing_reservation

                refund_billing_reservation.delay(
                    str(getattr(reservation, "reservation_id", reservation)),
                    reason,
                )
            except Exception:
                logger.exception("Could not enqueue image refund; periodic reconciliation remains active")

    @classmethod
    def _settle_image_reservation(cls, reservation, *, reason: str, deadline: float) -> None:
        """Settle under the DB budget; reconciliation repairs a timed-out settle."""
        if reservation is None:
            return
        try:
            cls._run_image_billing_operation(
                lambda: PaidFeature.settle(reservation, reason=reason),
                deadline,
            )
        except (OperationalError, ImageGenerationDeadlineExceeded):
            logger.exception(
                "Image settlement deferred for reservation=%s",
                getattr(reservation, "reservation_id", reservation),
            )

    @classmethod
    def _run_with_image_deadline(cls, operation, deadline: float):
        """Bound blocking provider/storage I/O independently of socket activity."""
        future = _IMAGE_IO_EXECUTOR.submit(operation)
        if future is None:
            cls._schedule_image_process_recycle()
            raise ImageGenerationDeadlineExceeded("image I/O capacity exhausted")
        try:
            return future.result(timeout=cls._remaining_image_timeout(deadline, 300))
        except FutureTimeoutError as exc:
            future.cancel()
            cls._schedule_image_process_recycle()
            raise ImageGenerationDeadlineExceeded from exc

    @staticmethod
    def _schedule_image_process_recycle() -> None:
        """
        Recycle a production process after abandoning blocking I/O.

        Python cannot safely kill a blocked thread. Railway restarts the web
        process, while Celery replaces a terminated prefork child. The delay
        lets the caller run its bounded refund/error path first.
        """
        from django.conf import settings

        if not getattr(settings, "IMAGE_IO_RECYCLE_PROCESS_ON_TIMEOUT", False):
            return
        if _IMAGE_PROCESS_RECYCLE_SCHEDULED.is_set():
            return
        _IMAGE_PROCESS_RECYCLE_SCHEDULED.set()
        logger.critical("Blocking image I/O exceeded its deadline; recycling process")
        timer = threading.Timer(5.0, os._exit, args=(70,))
        timer.daemon = True
        timer.start()

    @classmethod
    def _read_and_close_bounded_response(cls, response, *, deadline: float, max_bytes: int) -> bytes:
        """Read and dispose a streamed response inside the bounded worker."""
        try:
            return cls._read_bounded_response(response, deadline=deadline, max_bytes=max_bytes)
        finally:
            response.close()

    @classmethod
    def _read_bounded_response(cls, response, *, deadline: float, max_bytes: int) -> bytes:
        """Stream a response under one absolute deadline and byte ceiling."""
        content_length = response.headers.get("Content-Length")
        try:
            if content_length is not None and int(content_length) > max_bytes:
                raise ValueError("response_too_large")
        except (TypeError, ValueError) as exc:
            raise ValueError("invalid_or_oversized_response") from exc

        body = bytearray()
        for chunk in response.iter_content(chunk_size=64 * 1024):
            cls._remaining_image_timeout(deadline, 1)
            if not chunk:
                continue
            body.extend(chunk)
            if len(body) > max_bytes:
                raise ValueError("response_too_large")
        cls._remaining_image_timeout(deadline, 1)
        return bytes(body)

    @classmethod
    def _get_character_reference_bytes(
        cls,
        character: Character,
        deadline: Optional[float] = None,
    ) -> "Optional[bytes]":
        """
        Read the character's avatar bytes for use as a fal.ai Seedream edit
        reference, via the Django storage API (``avatar.open()/read()``).

        Because media lives in the shared Railway S3-compatible Bucket (or a
        local filesystem in dev/tests), the SAME storage backend serves both the
        web service and the Celery worker, so a direct storage read works from
        either process. Returns avatar bytes, or None when no usable reference
        exists.
        """
        avatar = getattr(character, "avatar", None)
        if not avatar:
            return None

        def read_avatar():
            avatar.open("rb")
            try:
                return avatar.read()
            finally:
                avatar.close()

        try:
            data = cls._run_with_image_deadline(read_avatar, deadline) if deadline is not None else read_avatar()
        except SoftTimeLimitExceeded:
            raise
        except ImageGenerationDeadlineExceeded:
            raise
        except Exception:
            logger.warning(
                "reference_fetch: could not read avatar via storage for character_id=%s",
                character.character_id,
                exc_info=True,
            )
            return None

        if data:
            logger.info(
                "reference_fetch: loaded avatar via storage for character_id=%s (%d bytes)",
                character.character_id,
                len(data),
            )
        else:
            logger.warning(
                "reference_fetch: avatar storage read returned no data for character_id=%s",
                character.character_id,
            )
        return data

